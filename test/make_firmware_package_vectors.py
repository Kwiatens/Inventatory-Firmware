"""Write test/firmware_package_vectors.h: signed package prefixes for test_firmware_package.cpp.

Each run makes two throwaway keys, so the bytes change, but the tests do not. Run from the
repository root after changing the package format:

    python3 test/make_firmware_package_vectors.py
"""

import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import sign_firmware as sf  # noqa: E402

OUT = ROOT / "test" / "firmware_package_vectors.h"
PRODUCT = "Inventatory-Scanner-R1"
HARDWARE = "waveshare-esp32s3-nano"
VERSION = "0.2.0"
COUNTER = 2
# Larger than one chunk, and not a multiple of it.
IMAGE_SIZE = 20000


def test_image():
    # Must match testImageByte() in test_firmware_package.cpp.
    return bytes((index * 31 + 7) & 0xFF for index in range(IMAGE_SIZE))


def c_array(name, data):
    lines = [f"constexpr uint8_t {name}[{len(data)}] = {{"]
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    image_hash = hashlib.sha256(test_image()).digest()
    with tempfile.TemporaryDirectory() as folder:
        keys = []
        for name in ("a", "b"):
            path = Path(folder) / f"{name}.pem"
            subprocess.run(["openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256",
                            "-out", str(path)], check=True, capture_output=True)
            keys.append((path, sf.public_key_from_private(path)))
        (key_a, public_a), (key_b, public_b) = keys

        def prefix(key=key_a, public=public_a, product=PRODUCT, hardware=HARDWARE, counter=COUNTER,
                   size=IMAGE_SIZE, reserved=b""):
            header = sf.build_header(public, product, hardware, VERSION, counter, size, image_hash, reserved)
            return header + sf.sign_header(key, header)

        vectors = [
            ("kVectorPublicKeyA", public_a),
            ("kVectorPublicKeyB", public_b),
            ("kVectorValid", prefix()),
            ("kVectorSignedByB", prefix(key=key_b, public=public_b)),
            ("kVectorWrongProduct", prefix(product="Inventatory-Scan-R2")),
            ("kVectorWrongHardware", prefix(hardware="other-board")),
            ("kVectorCounterOne", prefix(counter=1)),
            ("kVectorOversized", prefix(size=sf.PARTITION_BYTES + 1)),
            ("kVectorReservedSet", prefix(reserved=b"\x01")),
        ]

    body = "\n\n".join(c_array(name, data) for name, data in vectors)
    OUT.write_text(f"""// SPDX-FileCopyrightText: 2026 Paweł Kwiatkowski
// SPDX-License-Identifier: GPL-3.0-only

// Generated by test/make_firmware_package_vectors.py; do not edit. Throwaway test keys, image of
// {IMAGE_SIZE} bytes (testImageByte), version {VERSION}, security counter {COUNTER}.
#pragma once

#include <cstdint>

namespace firmware_vectors {{

constexpr uint32_t kVectorImageSize = {IMAGE_SIZE};
constexpr uint32_t kVectorSecurityCounter = {COUNTER};
constexpr char kVectorVersion[] = "{VERSION}";

{body}

}}  // namespace firmware_vectors
""", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
